"""Screenshots for the site: import them, size them for the web, and write site/manifest.js.

    py tools\\build_assets.py                          rebuild site/manifest.js from assets/<slug>/
    py tools\\build_assets.py --import assets\\STI      convert <slug>-NN-name.png files from a folder first
    py tools\\build_assets.py --import assets\\STI --replace
                                                     ...and drop each imported game's old screenshots

Imported files are named <slug>-<NN>-<words>.png (or .jpg/.webp), e.g. `nighthunt-03-glassing-a-buck.png`. Each
becomes assets/<slug>/<NN>-<words>.webp (at most 1920 px wide) plus a small copy in assets/<slug>/thumbs/. The words
become the caption ("Glassing a buck"). Files whose prefix isn't a known game are skipped and listed.

Needs Pillow for --import:  py -m pip install --user pillow
"""
from pathlib import Path
import argparse
import json
import re

root = Path(__file__).resolve().parent.parent
assets = root / 'assets'
GAMES = ['offrecord', 'stonethrone', 'boredtodepth', 'nighthunt', 'crowdcontrol']   # site/games.js slugs
EXTS = {'.png', '.jpg', '.jpeg', '.webp'}
FULL_W, THUMB_W = 1920, 480
NAME = re.compile(r'^(?P<slug>[a-z0-9]+)-(?P<rest>\d+-.+)$', re.I)


def import_folder(src, replace):
    from PIL import Image
    done, skipped = {}, []
    files = sorted(p for p in Path(src).iterdir() if p.is_file() and p.suffix.lower() in EXTS)
    plan = {}
    for p in files:
        m = NAME.match(p.stem)
        if not m or m['slug'].lower() not in GAMES:
            skipped.append(p.name)
            continue
        plan.setdefault(m['slug'].lower(), []).append((p, m['rest'].lower()))
    for slug, items in plan.items():
        out = assets / slug
        if replace and out.exists():
            for old in out.rglob('*'):
                if old.is_file() and old.suffix.lower() in EXTS:
                    old.unlink()
        (out / 'thumbs').mkdir(parents=True, exist_ok=True)
        for p, rest in items:
            with Image.open(p) as im:
                im = im.convert('RGB')
                for width, folder, quality in ((FULL_W, out, 82), (THUMB_W, out / 'thumbs', 70)):
                    copy = im.copy()
                    if copy.width > width:
                        copy = copy.resize((width, round(copy.height * width / copy.width)), Image.LANCZOS)
                    copy.save(folder / f'{rest}.webp', 'WEBP', quality=quality, method=6)
            done[slug] = done.get(slug, 0) + 1
    for slug, n in done.items():
        print(f'imported {n} into assets/{slug}/')
    if skipped:
        print('skipped (no known game prefix): ' + ', '.join(skipped))


def url(path):
    return '/'.join(part.replace(' ', '%20') for part in path.relative_to(root).parts)


def caption(stem):
    words = re.sub(r'^\d+[-_ ]*', '', stem).replace('-', ' ').replace('_', ' ').strip()
    return words[:1].upper() + words[1:] if words else ''


def manifest():
    payload = {}
    for folder in sorted(p for p in assets.iterdir() if p.is_dir() and p.name in GAMES):
        shots = []
        for p in sorted((p for p in folder.iterdir() if p.is_file() and p.suffix.lower() in EXTS), key=lambda p: p.name.lower()):
            thumb = folder / 'thumbs' / p.name
            shots.append({'src': url(p), 'thumb': url(thumb) if thumb.exists() else url(p), 'title': caption(p.stem)})
        if shots:
            payload[folder.name] = shots
    out = root / 'site' / 'manifest.js'
    out.write_text('// Generated by tools/build_assets.py. Do not edit by hand.\nwindow.SQT_SCREENSHOTS = '
                   + json.dumps(payload, indent=2) + ';\n', encoding='utf-8')
    for slug, shots in payload.items():
        print(f'{slug}: {len(shots)} screenshots')


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--import', dest='src', help='folder of <slug>-NN-name images to convert first')
    ap.add_argument('--replace', action='store_true', help="remove each imported game's existing screenshots first")
    args = ap.parse_args()
    if args.src:
        import_folder(args.src, args.replace)
    manifest()
