"""Regenerate site/manifest.js from the images in assets/<game-slug>/.

Each folder under assets/ is one game; its PNG, JPG and WebP files become that game's screenshot gallery, sorted by
file name. Paths are written relative to the site root.
"""
from pathlib import Path
import json

root = Path(__file__).resolve().parent.parent
assets = root / 'assets'
EXTS = {'.png', '.jpg', '.jpeg', '.webp'}


def url(path):
    return '/'.join(part.replace(' ', '%20') for part in path.relative_to(root).parts)


payload = {}
for folder in sorted(p for p in assets.iterdir() if p.is_dir()):
    images = sorted((p for p in folder.rglob('*') if p.is_file() and p.suffix.lower() in EXTS), key=lambda p: p.name.lower())
    if images:
        payload[folder.name] = [url(p) for p in images]

out = root / 'site' / 'manifest.js'
out.write_text('// Generated by tools/build_assets.py. Do not edit by hand.\nwindow.SQT_SCREENSHOTS = '
               + json.dumps(payload, indent=2) + ';\n', encoding='utf-8')
for slug, images in payload.items():
    print(f'{slug}: {len(images)} screenshots')
